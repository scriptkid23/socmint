/**
 * Bundles the in-page wallet provider (libs/browser-core/.../inpage/provider-entry.ts)
 * into a single minified IIFE and writes it as a string constant the Node code
 * can inject via context.addInitScript.
 *
 * Re-run after editing provider-entry.ts:  node scripts/build-wallet-inpage.mjs
 */
import { build } from 'esbuild';
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const entry = join(root, 'libs/browser-core/src/lib/wallet/inpage/provider-entry.ts');
const out = join(root, 'libs/browser-core/src/lib/wallet/inpage/inpage-bundle.generated.ts');

const result = await build({
  entryPoints: [entry],
  bundle: true,
  format: 'iife',
  platform: 'browser',
  target: 'es2020',
  minify: true,
  legalComments: 'none',
  write: false,
});

const code = result.outputFiles[0].text;
const banner = '/* AUTO-GENERATED by scripts/build-wallet-inpage.mjs. Do not edit by hand. */\n/* eslint-disable */\n';
writeFileSync(out, `${banner}export const INPAGE_WALLET_BUNDLE = ${JSON.stringify(code)};\n`);

console.log(`Wrote ${out} (${(code.length / 1024).toFixed(1)} KB bundle)`);
